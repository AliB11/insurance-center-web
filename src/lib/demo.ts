/**
 * ترتیب چرخشی دسته‌ها (اندیس SPECS) با وزن نزدیک به فهرست‌های واقعی:
 * داروخانه، آزمایشگاه و دندانپزشکی بیشترند و دیالیز کمتر.
 */
const MIX = [1, 2, 4, 1, 3, 6, 1, 8, 0, 5, 2, 9, 4, 1, 7, 3, 2, 6];

/** شماره‌های ساختگی تهران با الگوی ۰۲۱-۰۰۰۰xxxx — عمداً غیرواقعی */
function fakePhone(n: number): Phone {
  const tail = String(1000 + (n % 8999));
  return { label: `${AREA_CODE}-0000${tail}`, tel: `${AREA_CODE}0000${tail}` };
}

/** نقطهٔ تقریبی و قطعی اطراف مرکز محله/شهر (step درجه برای هر گام؛ حداکثر ۱۰ گام). */
function demoPoint(center: [number, number], seedA: number, seedB: number, step: number): Coordinates {
  const jitter = (seed: number) => (((seed * 37) % 21) - 10) * step;
  return {
    lat: Number((center[0] + jitter(seedA)).toFixed(6)),
    lng: Number((center[1] + jitter(seedB)).toFixed(6)),
  };
}

function build(): Center[] {
  const list: Center[] = [];
  const specUse = new Map<Spec, number>();
  const used = new Set<string>();
  let n = 0;
  REGIONS.forEach((region, r) => {
    // محله‌های تهران ۴ تا ۸ مرکز و شهرهای اطراف ۱ تا ۴ مرکز؛ مثل فهرست واقعی، بیشتر مراکز در شهر تهران‌اند
    const howMany = region.area ? 4 + ((r * 3) % 5) : 1 + ((r * 7) % 4);
    for (let k = 0; k < howMany; k++) {
      const spec = SPECS[MIX[n % MIX.length]];
      const use = specUse.get(spec) ?? 0;
      specUse.set(spec, use + 1);
      // نام + آدرس یکتا (کلید علاقه‌مندی‌ها بر همین پایه است)
      let name = '';
      let address = '';
      for (let attempt = 0; attempt < 12; attempt++) {
        const base = spec.prefix[(use + r + attempt) % spec.prefix.length];
        name = `${base} ${region.area ?? region.city}`;
        const street = region.streets[(n + k + attempt) % region.streets.length];
        const detail = spec.details[(use + attempt) % spec.details.length];
        // مثل فهرست‌های واقعی تهران، گاهی نام شهر در ابتدای آدرس می‌آید و گاهی نه
        address = region.area
          ? `${(n + k) % 2 ? 'تهران، ' : ''}${street}، ${detail}`
          : `${region.written ?? region.city}، ${street}، ${detail}`;
        if (!used.has(`${name}|${address}`)) break;
      }
      used.add(`${name}|${address}`);
      const phones: Phone[] = [fakePhone(n * 3 + k)];
      if ((n + k) % 3 === 0) phones.push(fakePhone(n * 5 + k + 4000));
      const desc = (n + k) % 5 === 0 ? 'پیش از مراجعه، هماهنگی تلفنی لازم است.' : '';
      const coordinates = demoPoint(region.center, n * 3 + k, n + k * 5, region.area ? 0.0011 : 0.0018);
      n++;
      const fields = {
        name, category: spec.category, kind: spec.kind, service: spec.service, province: PROVINCE,
        city: region.city, address, phones, discount: spec.discount, desc, extra: {},
      };
      list.push({
        id: list.length,
        coordinates,
        ...fields,
        sheet: 'دادهٔ نمونه',
        search: searchIndex(fields, region.area ?? ''),
        nameN: norm(name),
        locN: norm(`${PROVINCE} ${region.city}`),
        catN: norm(`${spec.category} ${spec.kind} ${spec.service}`),
      });
    }
  });
  return list;
}

let cache: Center[] | null = null;

export function demoCenters(): Center[] {
  if (!cache) {
    cache = build();
    cache.forEach((c, i) => (c.id = i));
  }
  return cache;
}

